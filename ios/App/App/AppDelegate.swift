import UIKit
import Capacitor
import AVFoundation

@UIApplicationMain
class AppDelegate: UIResponder, UIApplicationDelegate {

    var window: UIWindow?

    func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
        // WKWebView 里用 Web Audio 播放/合成的游戏音效默认走 ambient 音频类别，
        // 会被 iPhone 侧面的静音拨片直接掐掉，表现为"游戏完全没声音"。
        // 显式设为 playback（游戏/音乐类 App 的标准做法），让声音不依赖静音拨片。
        configureAudioSession()
        return true
    }

    /// 音频会话：playback 类别 + 激活，保证 Web Audio 能真正出声。
    private func configureAudioSession() {
        let session = AVAudioSession.sharedInstance()
        do {
            try session.setCategory(.playback, mode: .default, options: [])
            try session.setActive(true)
        } catch {
            print("[Audio] configureAudioSession failed: \(error)")
        }
    }

